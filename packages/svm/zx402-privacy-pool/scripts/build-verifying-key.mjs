#!/usr/bin/env node
/**
 * Generate `programs/zx402-privacy-pool/src/verifying_key.rs` from the
 * snarkjs-exported `public/circuits/withdraw/groth16_vkey.json`.
 *
 * Output convention:
 *   - All field elements are big-endian 32-byte arrays.
 *   - vk_alpha_g1   = 64 bytes (x || y)
 *   - vk_beta_g2    = 128 bytes (x.c0 || x.c1 || y.c0 || y.c1) — TWISTED order
 *     ⚠ snarkjs writes G2 affine coords as [[x.c0, x.c1], [y.c0, y.c1]];
 *     groth16-solana's verifier expects the BE bytes in the same nesting.
 *   - vk_gamma_g2, vk_delta_g2: same shape as beta_g2.
 *   - vk_ic        = (nPublic + 1) × 64 bytes.
 *
 * Run:
 *   node packages/svm/zx402-privacy-pool/scripts/build-verifying-key.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, "..", "..", "..", "..");
const VKEY_PATH = join(REPO, "public", "circuits", "withdraw", "groth16_vkey.json");
const OUT_PATH = join(__dirname, "..", "programs", "zx402-privacy-pool", "src", "verifying_key.rs");

const vkey = JSON.parse(readFileSync(VKEY_PATH, "utf8"));

if (vkey.protocol !== "groth16" || vkey.curve !== "bn128") {
  throw new Error(`unexpected vkey protocol/curve: ${vkey.protocol}/${vkey.curve}`);
}
const nPublic = vkey.nPublic;
if (vkey.IC.length !== nPublic + 1) {
  throw new Error(`vkey IC length ${vkey.IC.length} != nPublic+1 ${nPublic + 1}`);
}

/** decimal string → 32-byte big-endian Buffer */
function feBE(decStr) {
  const n = BigInt(decStr);
  if (n < 0n) throw new Error(`negative field element: ${decStr}`);
  const buf = Buffer.alloc(32);
  let v = n;
  for (let i = 31; i >= 0; i--) {
    buf[i] = Number(v & 0xffn);
    v >>= 8n;
  }
  if (v !== 0n) throw new Error(`field element does not fit in 32 bytes: ${decStr}`);
  return buf;
}

function g1(point) {
  // [x, y, 1] → 64 bytes (x || y), all big-endian.
  return Buffer.concat([feBE(point[0]), feBE(point[1])]);
}

function g2(point) {
  // [[x.c0, x.c1], [y.c0, y.c1], [1, 0]] → 128 bytes.
  // snarkjs nests as (X, Y, Z) where each is Fp2 = [c0, c1].
  // groth16-solana expects Fp2 in (c1, c0) order, big-endian:
  //   x.c1 || x.c0 || y.c1 || y.c0
  // Verified empirically on devnet 2026-05-10.
  return Buffer.concat([
    feBE(point[0][1]),
    feBE(point[0][0]),
    feBE(point[1][1]),
    feBE(point[1][0]),
  ]);
}

const alpha = g1(vkey.vk_alpha_1);
const beta = g2(vkey.vk_beta_2);
const gamma = g2(vkey.vk_gamma_2);
const delta = g2(vkey.vk_delta_2);
const ic = vkey.IC.map(g1);

function bytesArr(buf, indent = "    ") {
  const out = [];
  for (let i = 0; i < buf.length; i += 16) {
    out.push(
      indent +
        Array.from(buf.subarray(i, Math.min(i + 16, buf.length)))
          .map((b) => b.toString().padStart(3, " "))
          .join(", "),
    );
  }
  return out.join(",\n");
}

let rs = `// AUTO-GENERATED by scripts/build-verifying-key.mjs.
// Source: public/circuits/withdraw/groth16_vkey.json
// Do not edit by hand. Re-run the generator if the vkey changes.

#![allow(clippy::all)]

use groth16_solana::groth16::Groth16Verifyingkey;

/// Number of public signals the withdraw circuit emits.
/// 2 outputs (newCommitmentHash, existingNullifierHash) + 6 public inputs.
pub const N_PUBLIC: usize = ${nPublic};

const VK_IC: [[u8; 64]; ${ic.length}] = [
${ic
  .map(
    (buf, idx) =>
      `    // IC[${idx}]\n    [\n${bytesArr(buf, "        ")},\n    ]`,
  )
  .join(",\n")},
];

pub const VERIFYING_KEY: Groth16Verifyingkey<'static> = Groth16Verifyingkey {
    nr_pubinputs: N_PUBLIC,
    vk_alpha_g1: [
${bytesArr(alpha)},
    ],
    vk_beta_g2: [
${bytesArr(beta)},
    ],
    // NB: \`vk_gamme_g2\` (sic) — typo in groth16-solana 0.2 crate.
    vk_gamme_g2: [
${bytesArr(gamma)},
    ],
    vk_delta_g2: [
${bytesArr(delta)},
    ],
    vk_ic: &VK_IC,
};
`;

writeFileSync(OUT_PATH, rs);
console.log(`Wrote ${OUT_PATH} (${rs.length} bytes, IC=${ic.length})`);
